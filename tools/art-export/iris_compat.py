#!/usr/bin/env python3
"""Local Iris + Complementary Shaderpack Mapping Merger (docs/design/32-art-audio.md section 6.2C & 6.3).

Reads all generated `assets/<modid>/iris/tc_iris_mapping.properties` fragments across the
repository, inspects a user's local shaderpack (directory or .zip archive) to identify
Complementary Reimagined / Unbound version & material ID lines, and writes a LOCAL COPY
(`<shaderpack>-tc-compat` folder or `.zip`) without modifying or redistributing third-party
shaderpacks in place. For unknown shaderpacks, preserves Layer A (LabPBR 1.3 `_n`/`_s`) only
and emits an explicit user notice per section 6.3 Rule 1.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
import zipfile
from dataclasses import dataclass, field
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

import export as art_export  # noqa: E402

BEGIN_MARKER = "# BEGIN TC_IRIS_MAPPING (generated by tools/art-export/iris_compat.py)"
END_MARKER = "# END TC_IRIS_MAPPING"

CATEGORY_VANILLA_ANCHORS: dict[str, tuple[str, ...]] = {
    "foliage_waving": ("minecraft:short_grass", "minecraft:grass", "minecraft:wheat"),
    "leaves_waving": ("minecraft:oak_leaves", "minecraft:spruce_leaves"),
    "vine_waving": ("minecraft:vine", "minecraft:weeping_vines"),
    "water_like": ("minecraft:water",),
    "glass": ("minecraft:glass", "minecraft:white_stained_glass"),
    "ice": ("minecraft:ice", "minecraft:frosted_ice"),
    "emissive_full": ("minecraft:sea_lantern", "minecraft:glowstone", "minecraft:shroomlight"),
    "emissive_partial": ("minecraft:sculk_catalyst", "minecraft:enchanting_table", "minecraft:brewing_stand", "minecraft:campfire:lit=true"),
    "metal": ("minecraft:iron_block", "minecraft:copper_block"),
    "snow": ("minecraft:snow_block", "minecraft:powder_snow"),
    "lava_like": ("minecraft:lava", "minecraft:magma_block"),
}

COMPLEMENTARY_R5_DEFAULT_IDS: dict[str, str] = {
    "foliage_waving": "10004",
    "leaves_waving": "10008",
    "vine_waving": "10016",
    "water_like": "30000",
    "glass": "30008",
    "ice": "30012",
    "emissive_full": "10088",
    "emissive_partial": "10092",
    "metal": "10216",
    "snow": "10132",
    "lava_like": "10068",
}

COMPLEMENTARY_VERSION_RE = re.compile(
    r"Complementary\s*(?:Reimagined|Unbound)?[_\s-]*r?(\d+\.\d+(?:\.\d+)?)",
    re.IGNORECASE,
)
BLOCK_PROP_LINE_RE = re.compile(r"^(\s*block\.(\d+)\s*=)(.*)$")


@dataclass
class ShaderpackDetection:
    recognized: bool
    family: str
    version: str
    has_block_properties: bool
    message: str


@dataclass
class MergeResult:
    detection: ShaderpackDetection
    output_path: Path | None
    layer_b_applied: bool
    merged_categories: dict[str, int] = field(default_factory=dict)
    total_mapped_blocks: int = 0


def collect_repo_iris_mappings(repo_root: Path) -> dict[str, list[str]]:
    """Aggregate category.<cat>=... entries from all modules' tc_iris_mapping.properties."""
    merged: dict[str, set[str]] = {}
    for modid in art_export.MODULES:
        prop_file = art_export.mod_assets_dir(repo_root, modid) / "iris" / "tc_iris_mapping.properties"
        if not prop_file.exists():
            continue
        for raw_line in prop_file.read_text(encoding="utf-8").splitlines():
            line = raw_line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, val = line.split("=", 1)
            key = key.strip()
            if not key.startswith("category."):
                continue
            cat = key[len("category.") :]
            if cat not in art_export.VALID_IRIS_CATEGORIES:
                continue
            for bid in val.split():
                merged.setdefault(cat, set()).add(bid.strip())
    return {cat: sorted(ids) for cat, ids in sorted(merged.items()) if ids}


def _read_shaderpack_text_files(shaderpack_path: Path) -> dict[str, str]:
    """Read relevant metadata & block.properties files from either folder or .zip shaderpack."""
    found: dict[str, str] = {}
    candidates = ("shaders/block.properties", "shaders/shaders.properties", "README.txt", "pack.mcmeta")
    if shaderpack_path.is_dir():
        for rel in candidates:
            fp = shaderpack_path / rel
            if fp.exists():
                found[rel] = fp.read_text(encoding="utf-8", errors="replace")
    elif shaderpack_path.is_file() and shaderpack_path.suffix.lower() == ".zip":
        with zipfile.ZipFile(shaderpack_path, "r") as zf:
            names = set(zf.namelist())
            for rel in candidates:
                if rel in names:
                    found[rel] = zf.read(rel).decode("utf-8", errors="replace")
    else:
        raise FileNotFoundError(f"Shaderpack path not found or unsupported format: {shaderpack_path}")
    return found


def detect_shaderpack(shaderpack_path: Path) -> ShaderpackDetection:
    """Identify Complementary Reimagined/Unbound version; flag unknown shaderpacks for Layer-A fallback."""
    files = _read_shaderpack_text_files(shaderpack_path)
    has_bp = "shaders/block.properties" in files
    probe_text = "\n".join([shaderpack_path.name] + list(files.values()))

    m = COMPLEMENTARY_VERSION_RE.search(probe_text)
    if m and has_bp:
        ver = m.group(1)
        major = int(ver.split(".", 1)[0])
        if major >= 5:
            return ShaderpackDetection(
                recognized=True,
                family="Complementary",
                version=f"r{ver}",
                has_block_properties=True,
                message=f"Recognized Complementary r{ver}; Layer A (LabPBR) + Layer B (block.properties) enabled.",
            )
        return ShaderpackDetection(
            recognized=False,
            family="Complementary",
            version=f"r{ver}",
            has_block_properties=has_bp,
            message=f"Unsupported legacy Complementary r{ver} (< r5.0); keeping Layer A (LabPBR 1.3) only.",
        )

    if "complementary" in probe_text.lower() and has_bp and "block." in files["shaders/block.properties"]:
        return ShaderpackDetection(
            recognized=True,
            family="Complementary",
            version="r5.x",
            has_block_properties=True,
            message="Recognized Complementary r5.x block.properties layout; Layer A + Layer B enabled.",
        )

    return ShaderpackDetection(
        recognized=False,
        family="unknown",
        version="unknown",
        has_block_properties=has_bp,
        message=(
            "Unknown shaderpack version (32-art-audio.md section 6.3): skipping block.properties mutation. "
            "Enable Resource Pack PBR (LabPBR 1.3) in shader settings to use Layer A material maps."
        ),
    )


def merge_block_properties_text(original_text: str, mappings: dict[str, list[str]]) -> tuple[str, dict[str, int]]:
    """Idempotently merge non-solid Iris categories into Complementary block.properties text."""
    cleaned_lines: list[str] = []
    inside_managed = False
    for line in original_text.splitlines():
        if line.strip() == BEGIN_MARKER:
            inside_managed = True
            continue
        if line.strip() == END_MARKER:
            inside_managed = False
            continue
        if not inside_managed:
            cleaned_lines.append(line)

    anchor_to_prop_id: dict[str, str] = {}
    for line in cleaned_lines:
        m = BLOCK_PROP_LINE_RE.match(line)
        if not m:
            continue
        prop_id = m.group(2)
        tokens = set(m.group(3).split())
        for cat, anchors in CATEGORY_VANILLA_ANCHORS.items():
            if cat not in anchor_to_prop_id and any(a in tokens for a in anchors):
                anchor_to_prop_id[cat] = prop_id

    counts: dict[str, int] = {}
    by_prop_id: dict[str, list[str]] = {}
    for cat, block_ids in sorted(mappings.items()):
        if cat == "solid" or not block_ids:
            continue
        prop_id = anchor_to_prop_id.get(cat, COMPLEMENTARY_R5_DEFAULT_IDS.get(cat))
        if prop_id:
            counts[cat] = len(block_ids)
            by_prop_id.setdefault(prop_id, []).extend(block_ids)

    existing_prop_ids_seen: set[str] = set()
    updated_lines: list[str] = []
    for line in cleaned_lines:
        m = BLOCK_PROP_LINE_RE.match(line)
        if m and m.group(2) in by_prop_id and m.group(2) not in existing_prop_ids_seen:
            prop_id = m.group(2)
            existing_prop_ids_seen.add(prop_id)
            existing_tokens = [tok for tok in m.group(3).split() if not tok.startswith("tc")]
            combined = existing_tokens + sorted(set(by_prop_id[prop_id]))
            updated_lines.append(f"{m.group(1)} {' '.join(combined)}")
        else:
            updated_lines.append(line)

    footer_lines = [BEGIN_MARKER]
    for prop_id, ids in sorted(by_prop_id.items()):
        if prop_id not in existing_prop_ids_seen:
            footer_lines.append(f"block.{prop_id} = {' '.join(sorted(set(ids)))}")
    footer_lines.append(END_MARKER)

    while updated_lines and updated_lines[-1].strip() == "":
        updated_lines.pop()
    final_text = "\n".join(updated_lines + [""] + footer_lines) + "\n"
    return final_text, counts


def default_compat_output_path(shaderpack_path: Path) -> Path:
    if shaderpack_path.is_file() and shaderpack_path.suffix.lower() == ".zip":
        stem = shaderpack_path.stem
        if not stem.endswith("-tc-compat"):
            stem = f"{stem}-tc-compat"
        return shaderpack_path.with_name(f"{stem}.zip")
    name = shaderpack_path.name
    if not name.endswith("-tc-compat"):
        name = f"{name}-tc-compat"
    return shaderpack_path.parent / name


def collect_repo_mappings_checked(repo_root: Path) -> dict[str, list[str]]:
    mappings = collect_repo_iris_mappings(repo_root)
    if not mappings:
        raise RuntimeError(f"No tc_iris_mapping.properties found under {repo_root}; run export.py --tier 64 first.")
    return mappings


def merge_shaderpack_mappings(
    repo_root: Path,
    shaderpack_path: Path,
    output_path: Path | None = None,
    dry_run: bool = False,
) -> MergeResult:
    """Create a local shaderpack copy with merged TC Iris mappings when shaderpack version is supported."""
    shaderpack_path = shaderpack_path.resolve()
    detection = detect_shaderpack(shaderpack_path)
    mappings = collect_repo_mappings_checked(repo_root)

    if not detection.recognized:
        return MergeResult(
            detection=detection,
            output_path=None,
            layer_b_applied=False,
            merged_categories={},
            total_mapped_blocks=sum(len(v) for v in mappings.values()),
        )

    dest = (output_path or default_compat_output_path(shaderpack_path)).resolve()
    if dest == shaderpack_path:
        raise ValueError("Refusing to overwrite original third-party shaderpack in-place; specify a separate output copy.")

    files = _read_shaderpack_text_files(shaderpack_path)
    merged_bp, counts = merge_block_properties_text(files["shaders/block.properties"], mappings)

    if not dry_run:
        if shaderpack_path.is_dir():
            if dest.exists():
                shutil.rmtree(dest)
            shutil.copytree(shaderpack_path, dest)
            (dest / "shaders" / "block.properties").write_text(merged_bp, encoding="utf-8")
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            with zipfile.ZipFile(shaderpack_path, "r") as zin, zipfile.ZipFile(
                dest, "w", compression=zipfile.ZIP_DEFLATED
            ) as zout:
                for item in zin.infolist():
                    if item.filename == "shaders/block.properties":
                        zout.writestr(item, merged_bp.encode("utf-8"))
                    else:
                        zout.writestr(item, zin.read(item.filename))

    return MergeResult(
        detection=detection,
        output_path=dest,
        layer_b_applied=True,
        merged_categories=counts,
        total_mapped_blocks=sum(len(v) for v in mappings.values()),
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Merge SuperMC tc_iris_mapping.properties into a local copy of Complementary shaderpack."
    )
    parser.add_argument("--shaderpack", type=Path, required=True, help="Path to user's installed shaderpack (.zip or folder)")
    parser.add_argument("--output", type=Path, default=None, help="Output local copy path (defaults to <name>-tc-compat)")
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--dry-run", action="store_true", help="Inspect and compute merge without writing output copy")
    args = parser.parse_args(argv)

    res = merge_shaderpack_mappings(args.repo_root.resolve(), args.shaderpack, args.output, dry_run=args.dry_run)
    print(f"[iris_compat] {res.detection.message}")
    if res.layer_b_applied:
        print(f"[iris_compat] output={res.output_path} categories={res.merged_categories}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
