#!/usr/bin/env python3
"""Generate pure-vanilla-API Minecraft Java entity geometry classes from Blender-exported person_geometry.json.

Zero coupling to other mod gameplay classes so generated models compile standalone.
Target package: com.nightcity.tcivilization.client.model
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

PACKAGE_NAME = "com.nightcity.tcivilization.client.model"


def _fmt_float(val: float) -> str:
    rounded = round(float(val), 4)
    if abs(rounded) < 1e-6:
        rounded = 0.0
    text = f"{rounded:.4f}".rstrip("0").rstrip(".")
    if "." not in text:
        text += ".0"
    return f"{text}F"


def _render_part_pose(pose: dict[str, Any]) -> str:
    ox, oy, oz = pose.get("offset", [0.0, 0.0, 0.0])
    rx, ry, rz = pose.get("rotation", [0.0, 0.0, 0.0])
    if all(abs(v) < 1e-6 for v in (ox, oy, oz, rx, ry, rz)):
        return "PartPose.ZERO"
    if all(abs(v) < 1e-6 for v in (rx, ry, rz)):
        return f"PartPose.offset({_fmt_float(ox)}, {_fmt_float(oy)}, {_fmt_float(oz)})"
    return (
        f"PartPose.offsetAndRotation({_fmt_float(ox)}, {_fmt_float(oy)}, {_fmt_float(oz)}, "
        f"{_fmt_float(rx)}, {_fmt_float(ry)}, {_fmt_float(rz)})"
    )


def _render_cube_builder(boxes: list[dict[str, Any]]) -> str:
    if not boxes:
        return "CubeListBuilder.create()"
    parts = ["CubeListBuilder.create()"]
    for box in boxes:
        u, v = box["uv"]
        x0, y0, z0 = box["origin"]
        w, h, d = box["size"]
        deform = float(box.get("deformation", 0.0))
        mirror = bool(box.get("mirror", False))
        chain = f".texOffs({int(u)}, {int(v)})"
        if mirror:
            chain += ".mirror()"
        if abs(deform) > 1e-6:
            chain += (
                f".addBox({_fmt_float(x0)}, {_fmt_float(y0)}, {_fmt_float(z0)}, "
                f"{_fmt_float(w)}, {_fmt_float(h)}, {_fmt_float(d)}, new CubeDeformation({_fmt_float(deform)}))"
            )
        else:
            chain += (
                f".addBox({_fmt_float(x0)}, {_fmt_float(y0)}, {_fmt_float(z0)}, "
                f"{_fmt_float(w)}, {_fmt_float(h)}, {_fmt_float(d)})"
            )
        if mirror:
            chain += ".mirror(false)"
        parts.append(chain)
    return "\n                ".join(parts)


def _emit_part_tree(node: dict[str, Any], parent_var: str, lines: list[str]) -> None:
    part_name = node["name"]
    var_name = f"part_{part_name}"
    builder_expr = _render_cube_builder(node.get("boxes", []))
    pose_expr = _render_part_pose(node.get("pose", {}))
    children = node.get("children", [])
    if children:
        lines.append(
            f'        PartDefinition {var_name} = {parent_var}.addOrReplaceChild("{part_name}", {builder_expr}, {pose_expr});'
        )
        for child in children:
            _emit_part_tree(child, var_name, lines)
    else:
        lines.append(
            f'        {parent_var}.addOrReplaceChild("{part_name}", {builder_expr}, {pose_expr});'
        )


def _collect_part_names(nodes: list[dict[str, Any]], acc: list[str]) -> None:
    for node in nodes:
        acc.append(node["name"])
        _collect_part_names(node.get("children", []), acc)


def render_locations_java(spec: dict[str, Any]) -> str:
    mod_id = spec["mod_id"]
    entity_id = spec["entity_id"]
    textures = spec["textures"]
    return f"""package {PACKAGE_NAME};

import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.resources.Identifier;
import net.neoforged.api.distmarker.Dist;
import net.neoforged.api.distmarker.OnlyIn;

/**
 * Model layer locations, baked texture identifiers, and LOD distance thresholds
 * for {{@code {mod_id}:{entity_id}}} (32-art-audio.md section 4.2-4.3).
 *
 * <p>Generated by {{@code tools/art-export/blender/export_mc_entity_java.py}}.
 * Zero coupling to gameplay classes.
 */
@OnlyIn(Dist.CLIENT)
public final class PersonModelLocations {{
    public static final String MOD_ID = "{mod_id}";
    public static final Identifier PERSON_ID = Identifier.fromNamespaceAndPath(MOD_ID, "{entity_id}");

    public static final ModelLayerLocation LOD0 = new ModelLayerLocation(PERSON_ID, "lod0");
    public static final ModelLayerLocation LOD1 = new ModelLayerLocation(PERSON_ID, "lod1");
    public static final ModelLayerLocation LOD2 = new ModelLayerLocation(PERSON_ID, "lod2");

    public static final Identifier TEXTURE_LOD0_BASE = Identifier.fromNamespaceAndPath(MOD_ID, "{textures['lod0_base']}");
    public static final Identifier TEXTURE_LOD0_HAIR_E0 = Identifier.fromNamespaceAndPath(MOD_ID, "{textures['lod0_hair_e0']}");
    public static final Identifier TEXTURE_LOD0_OUTFIT_E0_HIDE = Identifier.fromNamespaceAndPath(MOD_ID, "{textures['lod0_outfit_e0_hide']}");
    public static final Identifier TEXTURE_LOD0_COMPOSITE_E0 = Identifier.fromNamespaceAndPath(MOD_ID, "{textures['lod0_composite_e0']}");
    public static final Identifier TEXTURE_LOD1_E0 = Identifier.fromNamespaceAndPath(MOD_ID, "{textures['lod1_e0']}");
    public static final Identifier TEXTURE_LOD2_E0 = Identifier.fromNamespaceAndPath(MOD_ID, "{textures['lod2_e0']}");

    public static final double LOD0_MAX_DISTANCE = 16.0D;
    public static final double LOD1_MAX_DISTANCE = 48.0D;
    public static final double LOD2_MAX_DISTANCE = 128.0D;

    private PersonModelLocations() {{
    }}

    /**
     * Selects the active LOD tier (0, 1, 2) or -1 when beyond render range.
     *
     * @param distanceBlocks Euclidean camera distance in blocks
     * @param entityLodScale client {{@code render.entity_lod_scale}} factor (clamped to [0.5, 2.0])
     * @return 0 for LOD0, 1 for LOD1, 2 for LOD2, or -1 if culled
     */
    public static int selectLodTier(double distanceBlocks, double entityLodScale) {{
        double scale = Math.clamp(entityLodScale, 0.5D, 2.0D);
        if (distanceBlocks <= LOD0_MAX_DISTANCE * scale) {{
            return 0;
        }}
        if (distanceBlocks <= LOD1_MAX_DISTANCE * scale) {{
            return 1;
        }}
        if (distanceBlocks <= LOD2_MAX_DISTANCE * scale) {{
            return 2;
        }}
        return -1;
    }}
}}
"""


def render_lod_geometry_java(class_name: str, lod_spec: dict[str, Any]) -> str:
    tex_w, tex_h = lod_spec["texture_size"]
    roots = lod_spec["parts"]
    part_names: list[str] = []
    _collect_part_names(roots, part_names)

    has_deformation = "new CubeDeformation(" in "\n".join(
        _render_cube_builder(n.get("boxes", [])) for n in _iter_nodes(roots)
    )

    imports = [
        "import net.minecraft.client.model.geom.PartPose;",
        "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
        "import net.minecraft.client.model.geom.builders.LayerDefinition;",
        "import net.minecraft.client.model.geom.builders.MeshDefinition;",
        "import net.minecraft.client.model.geom.builders.PartDefinition;",
        "import net.neoforged.api.distmarker.Dist;",
        "import net.neoforged.api.distmarker.OnlyIn;",
    ]
    if has_deformation:
        imports.insert(1, "import net.minecraft.client.model.geom.builders.CubeDeformation;")
    imports_text = "\n".join(sorted(imports))

    const_lines = [
        f'    public static final String PART_{name.upper()} = "{name}";'
        for name in part_names
    ]
    const_Lines_str = "\n".join(const_lines)

    body_lines: list[str] = []
    for root_node in roots:
        _emit_part_tree(root_node, "root", body_lines)
    body_str = "\n".join(body_lines)

    return f"""package {PACKAGE_NAME};

{imports_text}

/**
 * {lod_spec['description']}
 *
 * <p>Generated from Blender source {{@code {lod_spec['source_blend']}}}.
 * Dedicated non-player UV layout ({{@code {tex_w}x{tex_h}}}) per 32-art-audio.md section 4.3 rule 4.
 */
@OnlyIn(Dist.CLIENT)
public final class {class_name} {{
    public static final int TEXTURE_WIDTH = {int(tex_w)};
    public static final int TEXTURE_HEIGHT = {int(tex_h)};

{const_Lines_str}

    private {class_name}() {{
    }}

    public static LayerDefinition createBodyLayer() {{
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
{body_str}
        return LayerDefinition.create(mesh, TEXTURE_WIDTH, TEXTURE_HEIGHT);
    }}
}}
"""


def _iter_nodes(nodes: list[dict[str, Any]]):
    for n in nodes:
        yield n
        yield from _iter_nodes(n.get("children", []))


def generate_java_models(geometry_json: Path, output_dir: Path) -> list[Path]:
    spec = json.loads(geometry_json.read_text(encoding="utf-8"))
    output_dir.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []
    loc_file = output_dir / "PersonModelLocations.java"
    loc_file.write_text(render_locations_java(spec), encoding="utf-8")
    written.append(loc_file)

    class_map = {
        "lod0": "PersonLod0ModelGeometry",
        "lod1": "PersonLod1ModelGeometry",
        "lod2": "PersonLod2ModelGeometry",
    }
    for lod_key, class_name in class_map.items():
        lod_spec = spec["lods"][lod_key]
        target = output_dir / f"{class_name}.java"
        target.write_text(render_lod_geometry_java(class_name, lod_spec), encoding="utf-8")
        written.append(target)

    return written


def main() -> int:
    parser = argparse.ArgumentParser(description="Export Blender person geometry JSON to MC Java LayerDefinitions.")
    parser.add_argument("--input", required=True, type=Path, help="Path to person_geometry.json")
    parser.add_argument("--output-dir", required=True, type=Path, help="Target Java package directory")
    args = parser.parse_args()

    files = generate_java_models(args.input, args.output_dir)
    for f in files:
        print(f"Generated: {f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
